const dictionaries = { en, vi };
export type Lang = keyof typeof dictionaries;
export const LANGS: { id: Lang; name: string }[] = [
  { id: "en", name: "English" },
  { id: "vi", name: "Tiếng Việt" },
];

export function resolveLang(setting: string): Lang {
  if (setting === "en" || setting === "vi") return setting;
  return navigator.language.toLowerCase().startsWith("vi") ? "vi" : "en";
}

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = dictionaries[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Re-renders only when the language changes. */
export function useT() {
  const lang = useApp((st) => st.lang);
  return (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export function effortName(t: ReturnType<typeof useT>, id: string | null | undefined): string {
  if (!id) return "";
  const key = `effort.${id}` as Key;
  return key in en ? t(key) : id;
}

export function modeName(t: ReturnType<typeof useT>, id: string | null | undefined, fallback?: string): string {
  if (!id) return fallback || "";
  const key = `mode.${id}` as Key;
  return key in en ? t(key) : fallback || id;
}
